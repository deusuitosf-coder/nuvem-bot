export type Lang = "pt" | "en" | "es";

const verdicts = {
  pt: { "Pode fazer": "Pode fazer", Espere: "Espere", "Não faça": "Não faça", "Faça com cuidado": "Faça com cuidado" },
  en: { "Pode fazer": "Go ahead", Espere: "Wait", "Não faça": "Don't", "Faça com cuidado": "Careful" },
  es: { "Pode fazer": "Adelante", Espere: "Espera", "Não faça": "No lo hagas", "Faça com cuidado": "Con cuidado" },
} as const;

export function sayVerdict(lang: Lang, answer: string) {
  const table = verdicts[lang] as Record<string, string>;
  return table[answer] ?? answer;
}

